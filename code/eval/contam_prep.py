#!/usr/bin/env python3
"""Contamination pre-reg, Branch B: free, call-free input preparation.

  python contam_prep.py p1-filter   -> docs/paper/CONTAMINATION-P1-FILTER.txt
  python contam_prep.py p3-inputs   -> data/memorization-branchB/p3_inputs.json
  python contam_prep.py poly-inputs -> contam/poly_p1_filter.txt + contam/poly_p3_inputs.json
  python contam_prep.py prompts     -> print one rendered P1/P2/P3 prompt (no network)

p3-inputs reads base_commit file contents with `git show <sha>:<path>` from the full
(non-partial) clones under <EVAL_ROOT>/swebench/<slug>__idx. That is read-only: it never
fetches. No model calls anywhere in this file.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import contam_common as cc  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]


def _verified():
    inst = {x["instance_id"]: x for x in cc.load_json(cc.VER / "instances_verified.json")}
    gold = cc.load_json(cc.VER / "gold_patches.json")
    return inst, gold


def cmd_p1_filter(args) -> int:
    inst, gold = _verified()
    na = sorted(i for i in inst if cc.p1_filtered(inst[i]["problem_statement"], gold[i]))
    trunc_only = [i for i in na
                  if not cc.p1_filtered(inst[i]["problem_statement"][:cc.ISSUE_CHARS], gold[i])]
    body = "\n".join(na) + "\n"
    sha = hashlib.sha256(body.encode()).hexdigest()
    hdr = [
        "# CONTAMINATION-P1-FILTER.txt -- instances where probe P1 is NA",
        "# Companion to docs/paper/CONTAMINATION-PREREG.md (Branch B, probe P1).",
        "# Rule: P1 is NA for instance i iff ANY gold-file basename occurs in the FULL",
        "#   problem_statement of i as a case-sensitive plain substring. Gold files are the",
        "#   a/<path> sides of the 'diff --git a/<path> b/<path>' headers of the SWE-bench",
        "#   Verified gold patch (work/p5/gold_patches.json); basename =",
        "#   last '/'-separated component (extension included), e.g. 'query.py'.",
        "# Code: scripts/eval/contam_common.py::p1_filtered; generated by",
        "#   scripts/eval/contam_prep.py p1-filter.",
        f"# Count: {len(na)} of {len(inst)}. P1-eligible: {len(inst) - len(na)}.",
        "# Cross-check: identical to the design authority's side table",
        "#   %TEMP%/issue_names_gold.json field 'base' (133 True, 0 disagreements).",
        f"# Of these, {len(trunc_only)} match only beyond the {cc.ISSUE_CHARS}-char issue truncation "
        f"used in the prompts: {', '.join(trunc_only) or 'none'}.",
        f"# sha256 of the id list below (one id per line, trailing newline): {sha}",
        "",
    ]
    out = REPO_ROOT / "docs" / "paper" / "CONTAMINATION-P1-FILTER.txt"
    out.write_text("\n".join(hdr) + body, encoding="utf-8", newline="\n")
    side = Path(args.side_table) if args.side_table else None
    if side and side.exists():
        names = cc.load_json(side)
        dis = [i for i in inst if (i in na) != bool(names[i]["base"])]
        print(f"[side-table] disagreements vs {side}: {len(dis)} {dis[:5]}")
    print(f"[p1-filter] NA={len(na)} eligible={len(inst) - len(na)} sha256={sha} -> {out}")
    return 0


def cmd_p3_inputs(args) -> int:
    inst, gold = _verified()
    rows, na = {}, {}
    for i in sorted(inst):
        fc = cc.first_change_line(gold[i])
        if fc is None:
            na[i] = "no_preimage"
            continue
        path, L = fc
        clone = cc.IDX_CLONES / f"{inst[i]['repo'].replace('/', '__')}__idx"
        r = subprocess.run(["git", "-C", str(clone), "show", f"{inst[i]['base_commit']}:{path}"],
                           capture_output=True)
        if r.returncode:
            na[i] = "git_show_failed"
            continue
        text = r.stdout.decode("utf-8", errors="replace")
        prefix, target = cc.p3_split(text, L)
        if not prefix:
            na[i] = "empty_prefix"
            continue
        if cc.ngram_overlap(target, target) is None:
            na[i] = "target_lt_5_tokens"
            continue
        rows[i] = {"repo": inst[i]["repo"], "path": path, "first_change_line": L,
                   "prefix": prefix, "target": target}
    cc.CONTAM.mkdir(parents=True, exist_ok=True)
    out = cc.CONTAM / "p3_inputs.json"
    out.write_text(json.dumps({"rows": rows, "na": na}, indent=1, sort_keys=True), encoding="utf-8")
    from collections import Counter
    print(f"[p3-inputs] eligible={len(rows)} NA={len(na)} {dict(Counter(na.values()))}")
    print(f"[p3-inputs] sha256={cc.sha256_file(out)} -> {out}")
    return 0


def cmd_poly_inputs(args) -> int:
    """PolyBench-Python extension (pre-reg B.2): recomputed P1 filter + frozen P3 inputs.
    File contents come from the per-instance index worktrees <EVAL_ROOT>/polybench/wt/<iid>
    (checked out at base_commit; HEAD is verified). The repo clones there are partial
    (blob:none), so `git show` would fetch; reading the worktree files is read-only."""
    poly = cc.polybench_python()
    na_p1 = sorted(i for i, x in poly.items() if cc.p1_filtered(x["problem_statement"], x["patch"]))
    body = "\n".join(na_p1) + "\n"
    cc.CONTAM.mkdir(parents=True, exist_ok=True)
    (cc.CONTAM / "poly_p1_filter.txt").write_text(
        f"# PolyBench-Python P1-NA list (same rule as CONTAMINATION-P1-FILTER.txt); "
        f"{len(na_p1)} of {len(poly)}\n" + body, encoding="utf-8")
    rows, na = {}, {}
    for i in sorted(poly):
        x = poly[i]
        fc = cc.first_change_line(x["patch"])
        if fc is None:
            na[i] = "no_preimage"
            continue
        path, L = fc
        wt = cc.POLY / "wt" / i
        head = subprocess.run(["git", "-C", str(wt), "rev-parse", "HEAD"],
                              capture_output=True, text=True).stdout.strip()
        if head != x["base_commit"]:
            na[i] = f"worktree_head_mismatch:{head[:12]}"
            continue
        fp = wt / path
        if not fp.is_file():
            na[i] = "file_not_in_worktree"
            continue
        text = fp.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n")
        prefix, target = cc.p3_split(text, L)
        if not prefix:
            na[i] = "empty_prefix"
            continue
        if cc.ngram_overlap(target, target) is None:
            na[i] = "target_lt_5_tokens"
            continue
        rows[i] = {"repo": x["repo"], "path": path, "first_change_line": L,
                   "prefix": prefix, "target": target}
    out = cc.CONTAM / "poly_p3_inputs.json"
    out.write_text(json.dumps({"rows": rows, "na": na}, indent=1, sort_keys=True), encoding="utf-8")
    from collections import Counter
    print(f"[poly-p1-filter] NA={len(na_p1)} eligible={len(poly) - len(na_p1)} "
          f"sha256(ids)={hashlib.sha256(body.encode()).hexdigest()}")
    print(f"[poly-p3-inputs] eligible={len(rows)} NA={len(na)} {dict(Counter(v.split(':')[0] for v in na.values()))}")
    print(f"[poly-p3-inputs] sha256={cc.sha256_file(out)} -> {out}")
    return 0


def cmd_prompts(args) -> int:
    inst, gold = _verified()
    i = args.id
    x = inst[i]
    for name, msgs in (("P1", cc.p1_messages(x["repo"], x["problem_statement"])),
                       ("P2", cc.p2_messages(x["repo"], x["problem_statement"]))):
        print(f"===== {name} {i}")
        for m in msgs:
            print(f"--- {m['role']}\n{m['content']}")
    p3 = cc.CONTAM / "p3_inputs.json"
    if p3.exists():
        row = cc.load_json(p3)["rows"].get(i)
        if row:
            print(f"===== P3 {i}")
            for m in cc.p3_messages(row["repo"], row["path"], row["prefix"]):
                print(f"--- {m['role']}\n{m['content']}")
            print("--- (target, not sent)\n" + "\n".join(row["target"]))
    return 0


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("p1-filter")
    a.add_argument("--side-table", default=None)
    sub.add_parser("p3-inputs")
    sub.add_parser("poly-inputs")
    c = sub.add_parser("prompts")
    c.add_argument("--id", default="django__django-11099")
    args = ap.parse_args()
    return {"p1-filter": cmd_p1_filter, "p3-inputs": cmd_p3_inputs,
            "poly-inputs": cmd_poly_inputs, "prompts": cmd_prompts}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
